# Deskripsi: Menentukan apakah suatu karakter adalah huruf A

# Definisi dan Spesifikasi
# is_an_a: character -> boolean
# is_an_a(c) benar jika c adalah karakter 'A'

# Realisasi
def is_an_a(c: str) -> bool:
    return c == 'A'

# Aplikasi
print(is_an_a('A'))
print(is_an_a('B'))
print(is_an_a('a'))